/**
 * reporter.js
 * Custom Jest reporter that writes a Markdown test result file to
 * API_TEST_RESULTS.md at the project root after the test run completes.
 */
const fs = require("fs");
const path = require("path");

class MarkdownReporter {
  constructor(globalConfig, options) {
    this._globalConfig = globalConfig;
    this._options = options;
    this._results = [];
    this._suites = {};
  }

  onTestResult(_test, testResult) {
    for (const result of testResult.testResults) {
      const suite = result.ancestorTitles.join(" › ") || "Root";
      if (!this._suites[suite]) this._suites[suite] = [];
      this._suites[suite].push({
        name: result.title,
        status: result.status, // 'passed' | 'failed' | 'pending'
        duration: result.duration ?? 0,
        failureMessages: result.failureMessages ?? [],
      });
    }
  }

  onRunComplete(_contexts, results) {
    const now = new Date().toISOString().replace("T", " ").slice(0, 19);
    const totalTests = results.numTotalTests;
    const passedTests = results.numPassedTests;
    const failedTests = results.numFailedTests;
    const pendingTests = results.numPendingTests;
    const duration = (
      results.testResults.reduce(
        (acc, r) => acc + (r.perfStats?.runtime ?? 0),
        0,
      ) / 1000
    ).toFixed(2);

    const statusEmoji = failedTests === 0 ? "✅" : "❌";
    const lines = [];

    lines.push(`# API Test Results`);
    lines.push(``);
    lines.push(`> Generated: ${now} (UTC+7)`);
    lines.push(`> Project: VestaEdu-NextJS/backend`);
    lines.push(``);
    lines.push(`## Summary`);
    lines.push(``);
    lines.push(`| Metric | Value |`);
    lines.push(`|--------|-------|`);
    lines.push(
      `| Overall | ${statusEmoji} ${failedTests === 0 ? "ALL PASS" : "SOME FAILED"} |`,
    );
    lines.push(`| Total tests | ${totalTests} |`);
    lines.push(`| ✅ Passed | ${passedTests} |`);
    lines.push(`| ❌ Failed | ${failedTests} |`);
    lines.push(`| ⏸ Pending | ${pendingTests} |`);
    lines.push(`| Duration | ${duration}s |`);
    lines.push(``);

    if (failedTests > 0) {
      lines.push(`## ❌ Failed Tests`);
      lines.push(``);
      for (const [suite, tests] of Object.entries(this._suites)) {
        const failed = tests.filter((t) => t.status === "failed");
        if (failed.length === 0) continue;
        lines.push(`### ${suite}`);
        for (const t of failed) {
          lines.push(``);
          lines.push(`**${t.name}**`);
          if (t.failureMessages.length > 0) {
            lines.push("```");
            lines.push(t.failureMessages.join("\n").slice(0, 500));
            lines.push("```");
          }
        }
      }
      lines.push(``);
    }

    lines.push(`## Detailed Results by API Group`);
    lines.push(``);

    for (const [suite, tests] of Object.entries(this._suites)) {
      const passed = tests.filter((t) => t.status === "passed").length;
      const failed = tests.filter((t) => t.status === "failed").length;
      const suiteMark = failed === 0 ? "✅" : "❌";
      lines.push(
        `### ${suiteMark} ${suite} (${passed}/${tests.length} passed)`,
      );
      lines.push(``);
      lines.push(`| Test | Status | ms |`);
      lines.push(`|------|--------|----|`);
      for (const t of tests) {
        const mark =
          t.status === "passed"
            ? "✅ PASS"
            : t.status === "failed"
              ? "❌ FAIL"
              : "⏸ SKIP";
        lines.push(`| ${t.name} | ${mark} | ${t.duration} |`);
      }
      lines.push(``);
    }

    lines.push(`## Role Matrix Coverage`);
    lines.push(``);
    lines.push(`| Role | Endpoints Tested |`);
    lines.push(`|------|-----------------|`);
    lines.push(
      `| Public (no token) | /health, /api/blog GET, /api/course GET, /api/events GET, /api/quizzes GET, /api/categories GET, /api/instructors GET, /api/event-registrations POST |`,
    );
    lines.push(
      `| student | /api/me, /api/assigned-quizzes, /api/results/*, /api/course-registrations POST |`,
    );
    lines.push(
      `| teacher | Blog/Course/Event/Quiz/Question create+update+delete, /api/classes, /api/dashboard |`,
    );
    lines.push(
      `| admin | All of the above + /api/users, /api/create-admin, /api/instructors write, /api/categories delete |`,
    );
    lines.push(``);
    lines.push(`---`);
    lines.push(`*Generated by scripts/api-test/reporter.js*`);

    const outputPath = path.resolve(__dirname, "../../API_TEST_RESULTS.md");
    fs.writeFileSync(outputPath, lines.join("\n"), "utf8");
    console.log(`\n📄 Markdown report written to: ${outputPath}`);
  }
}

module.exports = MarkdownReporter;
